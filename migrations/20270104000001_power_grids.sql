-- Power grids per country and product power-supply profiles (ADR 0024).

-- Reference data, shared by all companies. A country can have several grids.
CREATE TABLE products.power_grids (
    id           uuid PRIMARY KEY,
    country_code char(2) NOT NULL,
    name         text NOT NULL CHECK (btrim(name) <> ''),
    -- Nominal voltage as quoted: phase-to-neutral for 1 phase, line-to-line for 3 phases.
    voltage_v    integer NOT NULL CHECK (voltage_v > 0),
    phases       smallint NOT NULL CHECK (phases IN (1, 3)),
    frequency_hz smallint NOT NULL CHECK (frequency_hz IN (50, 60)),
    active       boolean NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (country_code, voltage_v, phases, frequency_hz)
);

-- What a product can be powered from. No rows = not an electrical product.
CREATE TABLE products.product_power_supplies (
    id            uuid PRIMARY KEY,
    product_id    uuid NOT NULL REFERENCES products.products(id) ON DELETE CASCADE,
    current_type  text NOT NULL CHECK (current_type IN ('ac', 'dc')),
    voltage_v     integer NOT NULL CHECK (voltage_v > 0),
    -- NULL for DC.
    phases        smallint CHECK (phases IN (1, 3)),
    -- NULL = works on 50 and 60 Hz.
    frequency_hz  smallint CHECK (frequency_hz IN (50, 60)),
    tolerance_pct integer NOT NULL DEFAULT 10 CHECK (tolerance_pct BETWEEN 0 AND 50),
    created_at    timestamptz NOT NULL DEFAULT now(),
    CHECK ((current_type = 'dc' AND phases IS NULL AND frequency_hz IS NULL)
        OR (current_type = 'ac' AND phases IS NOT NULL))
);
CREATE UNIQUE INDEX product_power_supplies_uq ON products.product_power_supplies
    (product_id, current_type, voltage_v, COALESCE(phases, 0), COALESCE(frequency_hz, 0));

ALTER TABLE sales.quotations
    ADD COLUMN power_grid_id uuid REFERENCES products.power_grids(id);
ALTER TABLE sales.orders
    ADD COLUMN power_grid_id uuid REFERENCES products.power_grids(id);

